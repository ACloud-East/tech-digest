    /**
     * 判断文本是否与科技数码领域相关（加权判定 + 强非科技黑名单）
     * 规则：
     *   1) 命中「强非科技黑名单」→ 直接 false（反腐/命案/婚恋/赛事/娱乐/护肤/博物等必拒）
     *   2) 必须命中至少 1 个硬科技主题词（weight≥2），否则纯靠"小米/华为/微博"等品牌名不算
     *   3) score≥2 才放行（硬科技词命中即满足，软词累计 2 个也算，但前提是含 1 个硬词）
     */
    isRelevant(text) {
        if (!text) return false;
        const lowerText = text.toLowerCase();

        // 1) 强非科技黑名单：命中任一直接 false
        for (const w of this.HARD_ENT_TERMS) {
            if (this.kwMatch(lowerText, w)) return false;
        }

        // 2/3) 加权判定
        let hardCount = 0;  // 硬科技主题词命中数
        let score = 0;
        for (const [category, keywords] of Object.entries(this.keywords)) {
            const weight = this.categoryWeight[category] || 1;
            const isHard = weight >= 2;
            for (const keyword of keywords) {
                if (this.kwMatch(lowerText, keyword)) {
                    score += weight;
                    if (isHard) hardCount++;
                    break;
                }
            }
            if (score >= 2 && hardCount > 0) break;
        }

        // 至少要有 1 个硬科技主题词，否则即便有"小米/华为/微博"等品牌名也不放行
        if (hardCount === 0) return false;
        return score >= 2;
    },

    /**
     * 获取文本匹配到的领域分类
     * @param {string} text
     * @returns {string[]}
     */
    getCategories(text) {
        if (!text) return [];

        const lowerText = text.toLowerCase();
        const categories = [];

        for (const [category, keywords] of Object.entries(this.keywords)) {
            for (const keyword of keywords) {
                if (this.kwMatch(lowerText, keyword)) {
                    categories.push(category);
                    break;
                }
            }
        }

        return categories;
    },

